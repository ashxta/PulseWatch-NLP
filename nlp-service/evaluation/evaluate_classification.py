"""
Evaluates the news-category classifier (classical/statistical + ML NLP:
TF-IDF + Logistic Regression) and reports real, measured metrics.

Data split: `data/sample_news_categories.csv` is split once into a train
set and a held-out test set (70/30, stratified, fixed `random_state=42`
for reproducibility). No separate dev split, for the same reason as
evaluate_sentiment.py: no hyperparameter search is performed.

IMPORTANT — dataset size: `sample_news_categories.csv` is a small,
hand-written DEMO/SAMPLE dataset (40 rows across 9 categories — roughly
4 examples per class). This is enough to demonstrate the pipeline
end-to-end, not enough to claim production accuracy; several categories
will show 0 precision/recall/F1 on this split purely because the test
fold ends up with 1-2 examples of that class. See DATASET_SETUP.md to
scale up with real labeled data.

There is no transformer-based news-category classifier in this project
(the "classical vs modern" comparison for this specific task is
TF-IDF+LogReg vs the same classifier's own rule-based confidence
backstop — see classification.py's CONFIDENCE_THRESHOLD fallback logic
— not a FinBERT-style transformer, since no pretrained financial
news-category transformer is bundled or fetched here).

Run:
    python evaluation/evaluate_classification.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.pipeline.classification import NewsClassifier, DATA_PATH, _load_dataset

RANDOM_STATE = 42
TEST_SIZE = 0.3


def _print_confusion_note(metrics):
    print("Per-class precision/recall/F1 (0.0 for a class usually means the")
    print("test fold happened to get 0-1 examples of it — see the dataset-size")
    print("caveat in this script's docstring, not a modeling bug):\n")
    for label, stats in metrics["perClass"].items():
        print(f"  {label:<15} P={stats['precision']:.3f}  R={stats['recall']:.3f}  F1={stats['f1']:.3f}")


def main():
    texts, labels = _load_dataset(DATA_PATH)
    print(f"Dataset: {DATA_PATH.name} ({len(texts)} rows total) — DEMO/SAMPLE data, see DATASET_SETUP.md")
    print(f"Split: ~{int(len(texts) * (1 - TEST_SIZE))} train / ~{int(len(texts) * TEST_SIZE)} test "
          f"(stratified, random_state={RANDOM_STATE}); no separate dev set (no hyperparameter search).\n")

    classifier = NewsClassifier(random_state=RANDOM_STATE)
    metrics = classifier.evaluate()

    print("=== News category classifier: TF-IDF + Logistic Regression (classical/statistical + ML NLP) ===")
    print(json.dumps(metrics, indent=2))
    print()
    _print_confusion_note(metrics)

    report_path = Path(__file__).resolve().parent / "classification_metrics_report.md"
    with open(report_path, "w") as f:
        f.write("# News Category Classifier Evaluation\n\n")
        f.write("Generated by `evaluation/evaluate_classification.py`. Metrics below are measured, ")
        f.write(f"not invented, on a held-out test split of `{DATA_PATH.name}` "
                f"({len(texts)} rows — a demo/sample dataset; see DATASET_SETUP.md).\n\n")
        f.write("No transformer-based comparison is included for this task: this project does not "
                "bundle or fetch a pretrained financial news-category transformer model. The "
                "classifier's rule-based confidence backstop (classification.py) is a fallback for "
                "low-confidence predictions, not a second model to benchmark against.\n\n")
        f.write("## Classical: TF-IDF + Logistic Regression\n\n```json\n")
        f.write(json.dumps(metrics, indent=2))
        f.write("\n```\n")
    print(f"\nReport written to {report_path}")


if __name__ == "__main__":
    main()
