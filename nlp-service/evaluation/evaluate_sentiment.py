"""
Evaluates the sentiment models and reports real, measured metrics —
nothing here is a hardcoded/invented number.

Data split: `data/sample_phrasebank.csv` is split once into a train set
and a held-out test set (75/25, stratified, fixed `random_state=42` for
reproducibility). There is no separate dev/validation split, because
neither model here does any hyperparameter search that would need one
(the classical model uses fixed LogisticRegression defaults). If a
hyperparameter sweep is added later, split out a dev set at that point
rather than tuning against the test set.

IMPORTANT — dataset size: `sample_phrasebank.csv` is a small, hand-written
DEMO/SAMPLE dataset (75 rows), shipped so this evaluation runs without any
external download. It is not a substitute for the real Financial
PhraseBank (4800+ rows) referenced in DATASET_SETUP.md, and the accuracy
numbers below should be read as "the pipeline works and metrics are
computed correctly," not as production-grade sentiment accuracy.

Run:
    python evaluation/evaluate_sentiment.py

Models evaluated:
  - Classical baseline (TF-IDF + Logistic Regression) — always available,
    part of requirements.txt, no download needed.
  - FinBERT (transformer) — OPTIONAL. Only runs if `transformers` + `torch`
    are installed (requirements-transformers.txt) AND the
    `ProsusAI/finbert` checkpoint can be downloaded from huggingface.co.
    If unavailable, this script prints "Skipped: ..." and does NOT
    fabricate a number for that row.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.pipeline.sentiment import (
    ClassicalSentimentModel,
    TransformerSentimentModel,
    LABELS,
    DATA_PATH,
    _load_dataset,
)
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, f1_score, confusion_matrix

RANDOM_STATE = 42
TEST_SIZE = 0.25


def _print_confusion_matrix(cm, labels):
    header = "        " + "  ".join(f"{l[:4]:>4}" for l in labels)
    print(header)
    for label, row in zip(labels, cm):
        print(f"{label[:6]:>6}  " + "  ".join(f"{v:>4}" for v in row))


def main():
    texts, labels = _load_dataset(DATA_PATH)
    print(f"Dataset: {DATA_PATH.name} ({len(texts)} rows total) — DEMO/SAMPLE data, see DATASET_SETUP.md")
    print(f"Split: {int(len(texts) * (1 - TEST_SIZE))} train / {int(len(texts) * TEST_SIZE) or 1} test "
          f"(stratified, random_state={RANDOM_STATE}); no separate dev set (no hyperparameter search).\n")

    classical = ClassicalSentimentModel(random_state=RANDOM_STATE)
    classical_metrics = classical.evaluate()

    print("=== Classical model: TF-IDF + Logistic Regression (classical/statistical + ML NLP) ===")
    print(json.dumps(classical_metrics, indent=2))
    print("\nConfusion matrix (rows = true label, columns = predicted):")
    _print_confusion_matrix(classical_metrics["confusionMatrix"]["matrix"], LABELS)

    print("\n=== Transformer model: FinBERT (transformer-based NLP, OPTIONAL) ===")
    transformer_metrics = None
    try:
        transformer = TransformerSentimentModel()
        _, X_test, _, y_test = train_test_split(
            texts, labels, test_size=TEST_SIZE, random_state=RANDOM_STATE, stratify=labels,
        )
        preds = [transformer.predict(t).sentiment.lower() for t in X_test]
        acc = accuracy_score(y_test, preds)
        f1 = f1_score(y_test, preds, average="macro", labels=LABELS, zero_division=0)
        cm = confusion_matrix(y_test, preds, labels=LABELS)
        transformer_metrics = {
            "modelType": f"FinBERT ({TransformerSentimentModel.MODEL_NAME})",
            "accuracy": round(float(acc), 4),
            "macroF1": round(float(f1), 4),
            "testSize": len(X_test),
            "confusionMatrix": {"labels": LABELS, "matrix": cm.tolist()},
        }
        print(json.dumps(transformer_metrics, indent=2))
    except RuntimeError as e:
        print(f"Skipped (not installed / not available in this environment): {e}")
        print("Install with: pip install -r requirements-transformers.txt")
        print("Requires network access to huggingface.co to download the FinBERT checkpoint (~440MB) on first run.")

    report_path = Path(__file__).resolve().parent / "metrics_report.md"
    with open(report_path, "w") as f:
        f.write("# Sentiment Model Evaluation\n\n")
        f.write("Generated by `evaluation/evaluate_sentiment.py`. Metrics below are measured, ")
        f.write(f"not invented, on a held-out test split of `{DATA_PATH.name}` "
                f"({len(texts)} rows — a demo/sample dataset, not the full Financial PhraseBank; "
                f"see DATASET_SETUP.md).\n\n")
        f.write("## Classical: TF-IDF + Logistic Regression (always available)\n\n```json\n")
        f.write(json.dumps(classical_metrics, indent=2))
        f.write("\n```\n\n")
        f.write("## Transformer: FinBERT (optional, requires requirements-transformers.txt + model download)\n\n")
        if transformer_metrics:
            f.write("```json\n")
            f.write(json.dumps(transformer_metrics, indent=2))
            f.write("\n```\n")
        else:
            f.write("Not run in this environment — transformers/torch not installed or the FinBERT "
                    "checkpoint could not be downloaded. No number is reported here; re-run this "
                    "script after `pip install -r requirements-transformers.txt` to populate it.\n")
    print(f"\nReport written to {report_path}")


if __name__ == "__main__":
    main()
